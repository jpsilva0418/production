export const locales = ['en', 'pt', 'es'] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = 'en';

export const htmlLang: Record<Locale, string> = { en: 'en-US', pt: 'pt-BR', es: 'es-US' };
export const speechLang: Record<Locale, string> = { en: 'en-US', pt: 'pt-BR', es: 'es-US' };
export const localeName: Record<Locale, string> = { en: 'English', pt: 'Português', es: 'Español' };

export function isLocale(v: unknown): v is Locale {
  return typeof v === 'string' && (locales as readonly string[]).includes(v);
}

// URL scheme is the live site's, unchanged, so nothing indexed moves:
//   home:    /            /pt/home            /es/home
//   others:  /en/<slug>   /pt/<slug>          /es/<slug>
export function homePath(l: Locale) {
  return l === 'en' ? '/' : `/${l}/home`;
}
export function pagePath(l: Locale, slug: string) {
  return `/${l}/${slug}`;
}

